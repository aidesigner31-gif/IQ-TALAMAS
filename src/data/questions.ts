export const OVERRIDES_STORAGE_KEY = "iq_talmas_answer_overrides";

export function getOverrides(): Record<number, AnswerOverride> {
  try {
    return JSON.parse(localStorage.getItem(OVERRIDES_STORAGE_KEY) || "{}");
  } catch {
    return {};
  }
}

export function saveOverrides(overrides: Record<number, AnswerOverride>): void {
  localStorage.setItem(OVERRIDES_STORAGE_KEY, JSON.stringify(overrides));
}

export function clearOverrides(): void {
  localStorage.removeItem(OVERRIDES_STORAGE_KEY);
}

export function getActiveAdvancedQuestions(): AdvancedQuestion[] {
  const overrides = getOverrides();
  return defaultAdvancedQuestions.map(q => {
    const override = overrides[q.id];
    if (!override) return q;
    return {
      ...q,
      correctAnswer: override.correctAnswer ?? q.correctAnswer,
      lawCorrectIndex: override.lawCorrectIndex ?? q.lawCorrectIndex
    };
  });
}
